// 검색엔진·AI 검색용 구조화 데이터(문서 6장): WebApplication + FAQPage. FAQ는 화면의 FAQ와 같은 데이터에서 만들어 글자까지 같다.
// 가격(offers)·후기·별점은 넣지 않는다(문서 지시). 페이지 주소는 원본(canonical)이다.
export function testPageJsonLd(page: TestPage) {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebApplication",
        "@id": `${page.canonical}#app`,
        name: page.name,
        description: page.description,
        url: page.homeUrl,
        mainEntityOfPage: page.canonical,
        applicationCategory: "LifestyleApplication",
        operatingSystem: "Web",
        inLanguage: "ko-KR",
        isAccessibleForFree: true,
        publisher: { "@id": "https://www.ssolwellnesshouse.com/#org" },
      },
      {
        "@type": "FAQPage",
        mainEntity: page.faq.flatMap((g) => g.items).map(({ q, a }) => ({ "@type": "Question", name: q, acceptedAnswer: { "@type": "Answer", text: a } })),
      },
    ],
  };
}
