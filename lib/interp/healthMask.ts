// 직접 건강 표현 가리기(2026-10-18 owner 결정): 쏘웰라는 질병명·진단·약·치료 같은 건강 직접 정보를 수집하지 않고,
// "건강 때문에 슬프다·피곤하다" 같은 감정·컨디션만 둔다. 장부에 사용자 말 조각(evidence)을 저장하기 전에 이 함수로 건강 단어를 가린다.
// 대화에는 영향이 없다(답변은 그대로 들어 준다) — 저장되는 조각에서만 해당 어절이 "[건강]"으로 바뀐다.
// 예) "당뇨 진단받고 나서 계속 우울해요" → "[건강] 나서 계속 우울해요"  (우울한 마음은 남고 병명·진단만 사라짐)
// 범위는 A 단계: 질병명·진단·약·치료·병원. 몸 증상 표현(아프다·통증·잠이 안 와요)과 감정 말(우울해요·피곤해요)은 가리지 않는다.
export const MASK = "[건강]";

const WORD = "[가-힣A-Za-z0-9]";
const TRIGGERS = [
  // 암
  "(?:유방|위|폐|대장|간|갑상선|췌장|전립선|자궁경부|자궁|난소|피부|뇌|방광|신장|식도|구강|후두|골수|혈액)암",
  "암\\s*(?:진단|투병|환자|수술|치료|판정|선고|재발|검사)", "암이래", "암이라", "암에\\s*걸", "암을\\s*진단", "말기\\s*암", "백혈병", "림프종",
  // 질병
  "당뇨", "고혈압", "저혈압", "고지혈", "콜레스테롤", "갑상선", "디스크", "협착증", "관절염", "류마티스", "골다공증", "통풍", "아토피", "건선",
  "천식", "비염", "위염", "위궤양", "식도염", "과민성\\s*대장", "크론", "대상포진", "코로나", "독감", "(?<!눈이\\s?)(?<!눈\\s?)감기(?!고|며|면|어|지)", "폐렴", "결핵", "간염", "지방간",
  "편두통", "뇌전증", "간질", "파킨슨", "치매", "뇌졸중", "중풍", "심근경색", "협심증", "부정맥", "빈혈", "백내장", "녹내장", "중이염",
  "난임", "불임", "유산", "자궁근종", "자궁내막증", "다낭성",
  // 마음 건강의 병명(감정 말 "우울해요"는 해당 없음 — 병명 형태만)
  "우울증", "공황\\s*장애", "공황\\s*발작", "불안\\s*장애", "강박\\s*(?:증|장애)", "조울", "양극성", "ADHD", "adhd", "조현병", "섭식\\s*장애", "거식증", "폭식증",
  "PTSD", "ptsd", "외상\\s*후\\s*스트레스", "불면증", "해리\\s*장애", "자폐", "틱\\s*장애", "경계선\\s*성격",
  // 진단·약·치료·병원
  "진단\\s*(?:을\\s*)?받", "확진", "판정\\s*(?:을\\s*)?받", "처방", "복용", "항우울", "수면제", "신경안정", "항불안", "약물",
  "약(?:을|은|이)?\\s*(?:먹|복용|처방|끊|드시|타)", "정신과", "신경과", "병원(?!비)", "입원", "퇴원", "수술", "치료\\s*(?:를\\s*)?(?:받|중)", "검진",
  "재활", "물리치료", "투병", "링거", "MRI", "mri", "주사\\s*(?:를\\s*)?(?:맞|처방)",
];
// 트리거가 들어 있는 어절(공백으로 끊은 한 덩어리) 전체를 가린다 — 조사·어미가 남아 어색해지지 않게.
const RX = new RegExp(`${WORD}*(?:${TRIGGERS.join("|")})${WORD}*`, "g");

export function maskDirectHealth(text: string): { text: string; masked: boolean } {
  let masked = false;
  const out = text.replace(RX, () => { masked = true; return MASK; }).replace(/(?:\[건강\]\s*){2,}/g, `${MASK} `).replace(/\s+$/, "");
  return { text: out, masked };
}

// 장부 사건의 evidence에만 적용한다(점수·claim·확신도는 그대로).
export function maskEvents<T extends { evidence?: string }>(events: T[]): T[] {
  return events.map((e) => (typeof e.evidence === "string" ? { ...e, evidence: maskDirectHealth(e.evidence).text } : e));
}
