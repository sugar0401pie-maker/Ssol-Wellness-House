export const GENERAL_LAYER_ROUTES: readonly string[] = ["wellness", "life_decision"];

// 첫 번째 답변: 반영 + 한 칸 아래 후보를 고르게 묻는 질문 하나(층위 1~3).
export const LAYER_FIRST_TURN =
  "이 대화는 '한 번에 한 층씩 아래로' 내려가는 방식으로 진행합니다. 사용자가 말한 이유가 겉으로 드러난 이유라고 보고, 첫 답변에서는 마음을 한두 문장으로 반영한 뒤 질문을 하나만 하되 그 질문은 '그 아래에 어떤 마음이 있을 수 있는지' 2~3가지 후보를 보여 주고 어느 쪽에 가까운지 고르게 하세요. 질문은 물음표가 하나인 한 문장 안에 후보를 '~인지, ~인지, ~인지 — 어느 쪽에 가까우세요?'처럼 이어서 쓰세요(후보마다 따로 묻지 마세요). 후보는 반드시 사용자가 한 말에서 나올 수 있는 것만 쓰고, 각 후보는 '~일 수도 있을까요?'처럼 제안형으로 쓰세요. 이미 사용자가 한 단계 아래 마음까지 말했다면 거기서 한 칸 더 내려가는 후보를 쓰세요. 예: 사용자가 '단체운동은 적성에 안 맞아요'라고 하면 '사람들과 부대끼는 게 싫은 건지, 땀 나는 모습을 보이기 싫은 건지, 같이 하면 민폐가 될까 걱정되는 건지 — 어느 쪽에 가까우세요?'처럼 묻습니다. 사용자의 말에 없는 사정(가정·트라우마·병)을 후보에 넣지 마세요.";

// 두 번째 답변(기존: 대략적인 방향 + 더 구체적으로 원하는지 확인): 층위 4를 가설로 이름 붙인다.
export const LAYER_SECOND_TURN =
  "이번 답변에서는 사용자가 고른 말이나 한 말을 바탕으로 그 마음이 가리키는 성향이나 바라는 것(예: 뒤처지는 것 자체가 싫은 마음, 주목받고 싶지 않은 마음, 못하는 대로 받아들이고 싶은 마음, 스스로 정하고 싶은 마음)을 '~일 수도 있을까요?' 형태의 가설로 한두 가지만 짚어 주세요. 진단 용어·병명·유형 이름으로 단정하지 말고 '그런 사람'이라고 규정하지 마세요. 사용자가 '아니에요'라고 하면 바로 고치세요.";

// 세 번째 답변부터(기존: 정리 + 단기/중장기 3가지 제안): 해결책을 층위 4에 맞춘다.
export const LAYER_THIRD_TURN_ON =
  "제안하는 해결책은 지금까지 드러난 성향·바라는 것(층위 4)에 맞춘 것이어야 합니다. 예를 들어 자율성을 존중받고 싶은 마음이라면 혼자 페이스를 정하는 방식을, 주목받기 싫은 마음이라면 눈에 띄지 않게 시작하는 방식을 고르세요. 제안은 '해보는 건 어떨까요?' 형태로 하세요. 이번 답변에서는 새 질문으로 더 내려가지 말고, 들은 내용을 짧게 정리한 뒤 해결책을 먼저 제안하세요.";

// 층위 5 신호: 사용자가 "왜 이런 성향이 생겼는지·어떻게 관리/극복할지·더 깊이"를 직접 묻는 말. 코드로 알아보아 이때는 세션 제안을 답변에 반드시 넣게 한다(AI가 가끔 빠뜨려서 확인용으로 고정).
const LAYER5 = /(왜\s*(이런|이렇게|그런|제가|내가|저는|나는)[^.?!]{0,24}(생긴|생겼|된|그런\s*건|그런지)|어떻게\s*(관리|극복|고치|바꿔|다스리)|원인이?\s*(뭘까|뭔지|궁금|알고)|더\s*깊이\s*(알고|이야기|다루|살펴)|극복(하고|해보고)\s*싶)/;
export const isLayer5Signal = (text: string) => LAYER5.test(text);

// 층위 5·6 경계(항상 일반 대화 경로에 붙는다). alreadyOffered=true면 개인 웰니스 세션 안내를 이미 했으므로 되풀이하지 않는다.
export function layerHandoffBlock(opts: { humanSessionAlreadyOffered?: boolean; layer5Now?: boolean } = {}): string {
  const pitch = opts.humanSessionAlreadyOffered
    ? "개인 웰니스 세션 안내는 이미 했으므로 이번 대화에서 되풀이하지 마세요."
    : opts.layer5Now
    ? "지금 사용자가 바로 그 이야기를 더 깊이 다루고 싶어 합니다. 이번 답변에 '그 부분은 개인 웰니스 세션에서 상담사와 함께 더 깊이 살펴보는 건 어떨까요?'처럼 개인 웰니스 세션을 제안하는 문장을 한 문장 반드시 포함하세요(밀어붙이지 말고 제안형으로, 이번 대화에서 한 번만)."
    : "사용자가 그런 이야기를 더 깊이 다루고 싶어 하는 말을 할 때에 한해, 한 번만 '그 부분은 개인 웰니스 세션에서 상담사와 함께 더 깊이 살펴보는 건 어떨까요?'처럼 제안하세요. 사용자가 원하지 않는 한 먼저 권하거나 밀어붙이지 마세요.";
  return [
    "역할의 경계: 쏘웰라의 일은 사용자의 말을 한 층씩 내려가 마음의 바탕(성향·바라는 것)을 함께 알아차리고 그에 맞는 해결책을 제안하는 데까지입니다.",
    `'왜 그런 성향이 생겼는지', '어떻게 관리하고 싶은지', '적당히 받아들이며 극복하는 방법'을 깊이 찾는 일은 휴먼 웰니스 세션의 영역입니다. ${pitch}`,
    "왜 그런 성향이 생겼는지는 쏘웰라가 설명하거나 추측하지 마세요(어릴 때나 과거 경험 때문일 수 있다는 식의 말 포함). 사용자가 그 이유를 궁금해하면 한두 문장으로 그 궁금함을 받아 주고, 지금 할 수 있는 해결책을 이어서 제안하세요.",
    "성향이 생긴 이유의 병리적 원인을 밝히거나 약·진단·상담치료가 필요한지 판단하는 일은 웰니스 세션도 아닌 심리상담·의료의 영역입니다. 그런 이야기가 나오면 개인 웰니스 세션이 아니라 정신건강의학과·심리상담 같은 전문 기관과 상의해보도록 안내하고, 원인을 직접 추측해서 말하지 마세요.",
  ].join(" ");
}

// 일반 답변의 턴 수에 맞는 층위 지침. turnCount는 지금까지 한 쏘웰라 답변 수(0 = 첫 답변).
export function layerPacingBlock(turnCount: number): string {
  if (turnCount <= 0) return LAYER_FIRST_TURN;
  if (turnCount === 1) return LAYER_SECOND_TURN;
  return LAYER_THIRD_TURN_ON;
}
