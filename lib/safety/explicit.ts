// 구체 행동만: 신체 폭력 · 협박 · 통제 · 스토킹. (타로 목록에서 /폭력/·/감시/는 뺌 — 위 머리말 참고)
// /때려(?!치)/는 쏘웰라 V1(lib/safety/supplemental.ts)과 맞춤 — 타로 목록엔 없어 "저를 때려요"를 놓쳤다("때려치우다"는 제외).
const VIOLENCE_PHYSICAL = [/때리/, /때렸/, /때려(?!치)/, /(한테|에게)맞았/, /얻어맞/, /폭행/, /밀쳤/, /밀쳐/, /목을조/, /협박/, /위협/, /가만안두/, /죽어버리겠대/, /사진을뿌리/];
const VIOLENCE_CONTROL = [/휴대폰을검사/, /핸드폰을검사/, /폰을뒤/, /비번을알아야/, /비번을다/, /위치를공유하라/, /위치공유를강요/, /돈을뺏/, /가둬/, /가뒀/, /감금/, /스토킹/, /(저를|나를|계속)따라다(니|녀)/, /집앞에매일/, /번호바꿔도/];
const VIOLENCE_RE = [/(한테|에게)[^.?!]{0,6}(맞고있|맞고살|맞았|맞아요|맞는다|맞고지)/];

const DEFAULT_EXCLUDE = ["유서깊", "유서가깊", "사라지고싶을만큼", "사라지고싶었어요ㅋ", "투자해", "혼자살", "멍때리", "뼈때리", "협박범", "떨어져살기싫", "같이살기싫", "에서살기싫", "랑살기싫", "멀리살자신", "같이살자신", "떨어져살자신", "에서살자신"];

export type ExplicitLevel = "urgent" | "watch" | "none";
export type ExplicitResult = { level: ExplicitLevel; violence: "physical" | "control" | null; matched: string[] };

export function screenExplicit(text: string): ExplicitResult {
  const raw0 = String(text || "");
  let raw = raw0;
  let t = norm(raw0);
  for (const ex of DEFAULT_EXCLUDE) { t = t.split(norm(ex)).join(" "); raw = raw.split(ex).join(" "); }
  const hit = (list: RegExp[], s = t) => list.filter((re) => re.test(s)).map((re) => re.source);
  const tu = THREAT_REPORTED.reduce((s, re) => s.replace(new RegExp(re.source, "g"), " "), t);
  const u = [...hit([...URGENT, ...URGENT_RE], tu), ...URGENT_RAW.filter((re) => re.test(raw)).map((re) => re.source)];
  const w = u.length ? [] : hit([...WATCH, ...WATCH_RE]);
  const bare = /^(폭력|폭행|협박|위협|감시|스토킹|괴롭힘)[.!?~ㅠㅜ]*$/.test(t); // 낱말 하나만 쓴 글은 폭력으로 잡지 않음(무슨 일인지 먼저 들음)
  const vp = bare ? [] : [...new Set([...hit(VIOLENCE_PHYSICAL), ...hit(VIOLENCE_RE), ...hit(THREAT_REPORTED)])];
  const vc = bare ? [] : hit(VIOLENCE_CONTROL);
  const violence = vp.length ? "physical" : vc.length ? "control" : null;
  const level: ExplicitLevel = u.length ? "urgent" : w.length ? "watch" : "none";
  return { level, violence, matched: [...u, ...w, ...vp, ...vc] };
}
